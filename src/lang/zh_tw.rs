/// The Traditional Chinese of a note from the Vorax solver (`vorax::advisor`'s `Advice::note`), line by line; a
/// line whose pattern is not one of the solver's is returned as it is. Card names come from the Vorax name table
/// (`crate::vorax::names`), in English when it has no Chinese one. The patterns (`’` may also be `'`):
/// - `A Xenopanacea: always take it when it’s offered.`
/// - `{name}: always take it when it’s offered.`
/// - `{name}: {n} potion round(s) left, the chain needs {k}, so it is not taken.`
/// - `{name}: can’t be simulated; {n} potion round(s) left, the chain needs {k}.`
/// - `{name}: can’t be simulated.`
// Re-exported as `crate::lang::vorax_note` (src/lang/mod.rs).
pub fn vorax_note(en: &str) -> String {
    en.split('\n').map(vorax_note_line).collect::<Vec<_>>().join("\n")
}

/// One line of [`vorax_note`].
fn vorax_note_line(line: &str) -> String {
    let card = |en: &str| crate::vorax::names::names().cards.iter().find(|c| c.en == en).and_then(|c| c.zh.clone()).unwrap_or_else(|| en.to_string());
    if strip_end(line, "A Xenopanacea: always take it when it’s offered.") == Some("") {
        return "異種萬靈藥出現時一律拿。".to_string();
    }
    if let Some(name) = strip_end(line, ": always take it when it’s offered.") {
        return format!("「{}」出現時一律拿。", card(name));
    }
    if let Some(name) = strip_end(line, ": can’t be simulated.") {
        return format!("「{}」無法模擬。", card(name));
    }
    if let Some((name, left, need)) = line.strip_suffix(", so it is not taken.").and_then(|rest| chain_rounds(rest, ": ")) {
        return format!("「{}」不拿：藥劑回合只剩 {left} 回合，系列還要 {need} 步，走不完。", card(name));
    }
    if let Some((name, left, need)) = line.strip_suffix('.').and_then(|rest| chain_rounds(rest, "; ")).and_then(|(head, l, n)| strip_end(head, ": can’t be simulated").map(|name| (name, l, n))) {
        return format!("「{}」無法模擬；藥劑回合還剩 {left} 回合，系列還要 {need} 步。", card(name));
    }
    line.to_string()
}

/// `line` without `suffix`, where the `’` in `suffix` may also be written `'`.
fn strip_end<'a>(line: &'a str, suffix: &str) -> Option<&'a str> {
    line.strip_suffix(suffix).or_else(|| line.strip_suffix(suffix.replace('’', "'").as_str()))
}

/// `{head}{sep}{n} potion round(s) left, the chain needs {k}` as (head, n, k).
fn chain_rounds<'a>(s: &'a str, sep: &str) -> Option<(&'a str, u32, u32)> {
    let (s, need) = s.rsplit_once(", the chain needs ")?;
    let s = s.strip_suffix(" potion rounds left").or_else(|| s.strip_suffix(" potion round left"))?;
    let (head, left) = s.rsplit_once(sep)?;
    Some((head, left.parse().ok()?, need.parse().ok()?))
}

#[cfg(test)]
mod tests {
    use super::vorax_note;

    #[test]
    fn vorax_notes_are_translated() {
        assert_eq!(vorax_note("A Xenopanacea: always take it when it\u{2019}s offered."), "異種萬靈藥出現時一律拿。");
        assert_eq!(vorax_note("First Rite Holy Water: Confession: always take it when it\u{2019}s offered."), "「第一儀式聖水：告解」出現時一律拿。");
        assert_eq!(vorax_note("Dissection III: Craniotomy: always take it when it's offered."), "「解剖術 III：開顱術」出現時一律拿。");
        assert_eq!(
            vorax_note("First Rite Holy Water: Confession: 1 potion round left, the chain needs 3, so it is not taken."),
            "「第一儀式聖水：告解」不拿：藥劑回合只剩 1 回合，系列還要 3 步，走不完。"
        );
        assert_eq!(
            vorax_note("Dissection Infusion: Morbid Corpse: 2 potion rounds left, the chain needs 4, so it is not taken."),
            "「解剖浸液：病軀」不拿：藥劑回合只剩 2 回合，系列還要 4 步，走不完。"
        );
        // the offspring may have no Chinese name yet: only the sentence around it is checked
        let egg = vorax_note("F1 Gen: Parasite Egg: can\u{2019}t be simulated; 4 potion rounds left, the chain needs 3.");
        assert!(egg.starts_with('「') && egg.ends_with("」無法模擬；藥劑回合還剩 4 回合，系列還要 3 步。"), "{egg}");
        let cocoon = vorax_note("Incubation Elixir: Hollow Cocoon: can\u{2019}t be simulated.");
        assert!(cocoon.starts_with('「') && cocoon.ends_with("」無法模擬。"), "{cocoon}");
        // several lines, one at a time
        assert_eq!(
            vorax_note("Xenopanacea: Brood: always take it when it\u{2019}s offered.\nThird Rite Holy Water: Illumination: 0 potion rounds left, the chain needs 1, so it is not taken."),
            "「異種萬靈藥：育雛」出現時一律拿。\n「第三儀式聖水：啟蒙」不拿：藥劑回合只剩 0 回合，系列還要 1 步，走不完。"
        );
    }

    #[test]
    fn other_vorax_notes_stay_as_they_are() {
        for en in [
            "",
            "Something else.",
            "First Rite Holy Water: Confession: x potion rounds left, the chain needs 3, so it is not taken.",
            "First Rite Holy Water: Confession: 2 potion rounds left, the chain needs, so it is not taken.",
            "F1 Gen: Parasite Egg: 4 potion rounds left, the chain needs 3.",
        ] {
            assert_eq!(vorax_note(en), en);
        }
    }
}
